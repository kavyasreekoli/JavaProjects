package datatypes;

public class DataTypeCode5 {
	public static void main(String[] args) {
		long l1=126;
		System.out.println(l1);
		System.out.println("-----------");
		int i1=(int)l1;
		System.out.println(i1);
		System.out.println("-----------");
		short s1=(short)i1;
		System.out.println(s1);
		System.out.println("-----------");
		byte b1=(byte)s1;
		System.out.println(b1);
		System.out.println("-----------");
	}

}
