package datatypes;

public class DataTypeCode4 {
	public static void main(String[] args) {
		long l1=126;
		System.out.println(l1);
		System.out.println("-----------");
		int i1=l1;
		System.out.println(i1);
		System.out.println("-----------");
		short s1=i1;
		System.out.println(s1);
		System.out.println("-----------");
		byte b1=s1;
		System.out.println(b1);
		System.out.println("-----------");
	}
}
